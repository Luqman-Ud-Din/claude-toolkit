ROOT = Path(__file__).resolve().parents[1]


def frontmatter(path):
    text = path.read_text(encoding="utf-8-sig")
    parts = text.split("---", 2)
    if len(parts) != 3 or parts[0].strip():
        raise ValueError("missing frontmatter")
    fields = {}
    # Repository convention: single-line scalar name and description.
    for line in parts[1].splitlines():
        match = re.match(r"^(name|description):\s*(.*)$", line)
        if match:
            key, value = match.groups()
            if key in fields:
                raise ValueError("duplicate frontmatter key: " + key)
            if value.startswith('"'):
                value = json.loads(value)
            elif value.startswith("'") and value.endswith("'"):
                value = value[1:-1].replace("''", "'")
            fields[key] = value.strip()
    return fields


def inventory(root):
    errors, plugins, seen = [], [], {}
    try:
        market = json.loads((root / ".claude-plugin/marketplace.json").read_text(encoding="utf-8"))
        entries = market["plugins"]
        if not isinstance(entries, list):
            raise ValueError("plugins must be an array")
    except (OSError, ValueError, KeyError) as exc:
        return [], ["marketplace: " + str(exc)]
    listed = set()
    for entry in entries:
        try:
            name, source = entry["name"], entry["source"]
            if name in listed:
                errors.append("duplicate plugin: " + name)
            listed.add(name)
            if not isinstance(source, str) or not source.startswith("./"):
                raise ValueError("expected local ./ plugin source")
            folder = (root / source).resolve()
            if not folder.is_relative_to(root.resolve()) or not folder.is_dir():
                raise ValueError("plugin does not exist within marketplace: " + source)
            manifest = json.loads((folder / ".claude-plugin/plugin.json").read_text(encoding="utf-8"))
            if manifest.get("name") != name:
                errors.append("plugin name mismatch: " + source)
            plugins.append((folder, manifest, []))
        except (OSError, ValueError, KeyError, TypeError) as exc:
            errors.append("plugin entry: " + str(exc))
    # Validate every on-disk plugin, not just marketplace-listed ones.
    known = {p[0] for p in plugins}
    for folder in sorted((root / "plugins").glob("*")):
        if folder.is_dir() and folder.resolve() not in known:
            errors.append("unlisted plugin: " + folder.name)
            plugins.append((folder, {"name": folder.name}, []))
    for folder, manifest, skills in plugins:
        for skill in sorted((folder / "skills").glob("*")):
            if not skill.is_dir():
                continue
            path = skill / "SKILL.md"
            if not path.is_file():
                errors.append(str(skill) + ": missing SKILL.md")
                continue
            try:
                fields = frontmatter(path)
                name = fields.get("name", "")
                if name != skill.name:
                    errors.append(str(path) + ": name != folder name")
                if not fields.get("description") or fields["description"] in ("null", "~", "|", ">"):
                    errors.append(str(path) + ": description missing or unsupported (use a single-line scalar)")
                if name in seen:
                    errors.append("duplicate skill name: " + name)
                seen[name] = path
                skills.append((path, fields))
            except (OSError, ValueError) as exc:
                errors.append(str(path) + ": " + str(exc))
    return plugins, errors


