def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=["validate", "readme"])
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args()
    root = args.root.resolve()
    plugins, errors = inventory(root)
    if errors:
        print("\n".join("ERROR: " + error for error in errors))
        return 1
    if args.action == "readme":
        (root / "README.md").write_text(readme(plugins, root), encoding="utf-8", newline="\n")
        print("Generated README.md")
    else:
        print(f"PASS: {len(plugins)} plugins, {sum(len(row[2]) for row in plugins)} skills")
    return 0


